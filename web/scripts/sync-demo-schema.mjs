// Emit the landing demo's group schema from the canonical AGS4 dictionary, so
// the four tables on laterite.dev cannot describe a format the engine doesn't
// implement (#393, #396).
//
// The page draws PROJ → LOCA → SAMP → LLPL at their full KEY chains, and the
// chain IS the lesson: AGS4 has no ids and no joins, so a child group restates
// its parent's KEY headings verbatim. That is why LLPL is nine columns wide.
// A hand-written copy of those headings would be a second statement of the
// dictionary, and the failure it produces is the page teaching a KEY set the
// validator no longer agrees with — silently, because markup has no gate.
//
// Why a generated MODULE and not the runtime fetch the app uses: the app pulls
// the whole multi-edition dictionary (`sync-dict.mjs` → public/ags_dictionary.json)
// because it validates arbitrary files and needs all 174 groups. The landing
// page needs four, and a landing page is the one surface where the reader has
// not yet decided to care — it must not pay a dictionary download to draw a
// table. This slices those four at build time instead.
//
// Runs as the `prebuild:landing` / `predev:landing` hook, so the committed
// output is refreshed on every build and a stale hand-edit cannot survive one.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const here = path.dirname(fileURLToPath(import.meta.url));
const src = path.resolve(
  here,
  "../../rust-packages/laterite-ags4-reference/data/ags_dictionary.json",
);
const dst = path.resolve(here, "../landing/demo/schema.ts");

/** Every group the demo DRAWS: the descent chain parent-first, then TRAN,
 *  the cover sheet the File section renders (#527) — not part of the
 *  descent, but its headings come from the dictionary exactly like the
 *  chain's. Named like the Python gate's DRAWN so the two lists that must
 *  agree share a vocabulary. */
const DRAWN = ["PROJ", "LOCA", "SAMP", "LLPL", "TRAN"];

/** The headings each group DRAWS: its full KEY chain plus the few OTHER columns
 *  the demo needs to have something to say. Listing the extras here rather than
 *  taking the first N of the group keeps the choice explicit — LOCA has 47
 *  headings and the page shows five. The KEY set is never listed: it is read
 *  from the dictionary below, which is the half that must not drift. */
const EXTRAS = {
  PROJ: ["PROJ_NAME", "PROJ_CLNT"],
  LOCA: ["LOCA_TYPE", "LOCA_GL", "LOCA_REM", "LOCA_FDEP"],
  SAMP: [],
  LLPL: ["LLPL_LL", "LLPL_PL"],
  // The cover sheet draws its KEY plus every REQUIRED heading — leaving a
  // REQUIRED one out would seed a Rule 10b finding the page never narrates.
  TRAN: ["TRAN_DATE", "TRAN_PROD", "TRAN_STAT", "TRAN_AGS", "TRAN_RECV"],
};

let dict;
try {
  dict = JSON.parse(readFileSync(src, "utf8"));
} catch (err) {
  console.error(`sync-demo-schema: cannot read the dictionary at ${src}`);
  throw err;
}

const groups = [];
for (const code of DRAWN) {
  const g = dict.groups[code];
  if (!g) throw new Error(`sync-demo-schema: ${code} is not in the dictionary`);

  const wanted = new Set(EXTRAS[code]);
  // Dictionary order, not the order EXTRAS lists them in — Rule 7 checks
  // heading order, and a table drawn out of order would emit a file that fails
  // a rule the page never mentions.
  const headings = g.headings
    .filter((h) => h.status.includes("KEY") || wanted.has(h.name))
    .map((h) => ({
      name: h.name,
      key: h.status.includes("KEY"),
      required: h.status.includes("REQUIRED"),
      type: h.type,
      unit: h.unit ?? "",
      description: h.description,
    }));

  const missing = [...wanted].filter(
    (n) => !headings.some((h) => h.name === n),
  );
  if (missing.length) {
    throw new Error(
      `sync-demo-schema: ${code} has no ${missing.join(", ")} — the demo asks ` +
        `for a heading this dictionary edition does not define`,
    );
  }
  groups.push({ code, parent: g.parent, description: g.description, headings });
}

const body = groups
  .map(
    (g) =>
      `  {\n` +
      `    code: "${g.code}",\n` +
      `    parent: ${g.parent === null ? "null" : `"${g.parent}"`},\n` +
      `    description: ${JSON.stringify(g.description)},\n` +
      `    headings: [\n` +
      g.headings
        .map(
          (h) =>
            `      { name: "${h.name}", key: ${h.key}, required: ${h.required}, ` +
            `type: "${h.type}", ` +
            `unit: ${JSON.stringify(h.unit)}, description: ${JSON.stringify(h.description)} },`,
        )
        .join("\n") +
      `\n    ],\n` +
      `  },`,
  )
  .join("\n");

const out = `// GENERATED by web/scripts/sync-demo-schema.mjs — DO NOT EDIT.
// Source: rust-packages/laterite-ags4-reference/data/ags_dictionary.json
// (edition ${dict.default_edition}). Regenerate: npm run sync-demo-schema

export type DemoHeading = {
  /** The AGS4 heading, e.g. \`SAMP_TOP\`. */
  readonly name: string;
  /** True when the dictionary's status carries KEY (Rule 10a, the row's
   *  identity tuple) — the header's key glyph and the pinned column edge
   *  both key off this, and so does the parent-match tuple. */
  readonly key: boolean;
  /** True when the status carries REQUIRED (Rule 10b, present and
   *  non-empty) — an independent axis: TRAN holds REQUIRED-only headings,
   *  and PROJ_ID/TRAN_ISNO are both at once (#616's marker grammar). */
  readonly required: boolean;
  /** The AGS TYPE the file declares, e.g. \`2DP\`. */
  readonly type: string;
  /** The unit, or "" where the dictionary gives none. */
  readonly unit: string;
  readonly description: string;
};

export type DemoGroup = {
  readonly code: string;
  /** The dictionary's parent, which is what draws the chain. */
  readonly parent: string | null;
  readonly description: string;
  readonly headings: readonly DemoHeading[];
};

export const DEMO_GROUPS: readonly DemoGroup[] = [
${body}
] as const;

/** The KEY headings of \`code\`, in dictionary order — the tuple Rule 10c
 *  matches a child row against its parent by. */
export function keyHeadings(code: string): readonly string[] {
  const g = DEMO_GROUPS.find((x) => x.code === code);
  return g ? g.headings.filter((h) => h.key).map((h) => h.name) : [];
}
`;

writeFileSync(dst, out);
console.log(
  `  ok   ${path.relative(path.resolve(here, "../.."), dst)} — ${groups
    .map((g) => `${g.code}(${g.headings.length})`)
    .join(" → ")}`,
);
