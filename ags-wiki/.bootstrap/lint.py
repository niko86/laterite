# A11 — `<!-- historical -->` / `<!-- retired: TERM -->` exemption for the
# A2 retired-terms tripwire. Deliberately line-scoped, not page-scoped: a
# marker only exempts retired-term matches on its OWN line, so annotating
# one genuinely-historical sentence can't accidentally silence a live
# claim elsewhere on the same page. The generic form exempts every
# retired term on that line (for lines mentioning more than one); the
# specific form exempts only the named TERM, and TERM must be a real
# RETIRED_TERMS entry — an exemption citing an untracked term is either a
# typo or dead weight, either way reported as malformed rather than
# silently accepted. A marker that starts `<!-- historical`/`<!-- retired`
# but never closes isn't recognised as a marker at all (fails safe: the
# line stays flagged, not silently exempted).
# ---------------------------------------------------------------------------
