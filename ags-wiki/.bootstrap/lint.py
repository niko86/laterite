_BASENAME_INDEX: dict[str, list[str]] = {}
for _f in _TRACKED:
    _BASENAME_INDEX.setdefault(Path(_f).name, []).append(_f)


def categorize_dead_ref(path_str: str) -> tuple[str, str]:
    """Best-effort bucket for a dead ref, so the report-only run is
    triageable rather than just a wall of red. Never authoritative —
    a human still repoints in A4."""
    base = Path(path_str).name
    # the single highest-blast-radius known issue (plan §4 P1): the AGS5
    # dict was renamed in-place (ags4-core keeps ags_dictionary.json) AND
    # the *actual* ags5_dictionary.json moved to ags5/ with the rest of
    # the decoupled strand — flag it explicitly rather than let the
    # generic heuristics below guess at just one half of that.
    if base == "ags5_dictionary.json" and "laterite-ags4-core" in path_str:
        return (
            "dict-rename",
            "this dir now has ags_dictionary.json (AGS4 union); the "
            "AGS5 dict itself lives at "
            "ags5/rust-packages/laterite-ags5-db/data/ags5_dictionary.json",
        )
    # #177 decoupled the AGS5 strand into ags5/, same relative shape
    if (REPO_ROOT / "ags5" / path_str).exists():
        return ("ags5/ move", f"ags5/{path_str}")
    # exact basename lives elsewhere in the tracked tree (rename/relocate).
    # Generic basenames (lib.rs × 15, Cargo.toml × 21, …) need ranking, not
    # just "first 3 in git ls-files order" — sort by whole-path similarity
    # so e.g. dead `rust-packages/ags4-wasm/src/lib.rs` (pre-rename name)
    # surfaces the real match `rust-packages/laterite-ags4-wasm/src/lib.rs`
    # ahead of unrelated lib.rs files.
    candidates = [c for c in _BASENAME_INDEX.get(base, []) if c != path_str]
    if candidates:
        candidates.sort(
            key=lambda c: difflib.SequenceMatcher(None, path_str, c).ratio(),
            reverse=True,
        )
        shown = "; ".join(candidates[:3])
        if len(candidates) > 3:
            shown += f" (+{len(candidates) - 3} more)"
        return ("moved-not-deleted", shown)
    # near-miss basename in the same directory → likely typo, not a move
    parent = str(Path(path_str).parent)
    siblings = {Path(c).name for c in _TRACKED if str(Path(c).parent) == parent}
    close = difflib.get_close_matches(base, siblings, n=1, cutoff=0.75)
    if close:
        return ("typo?", f"{parent}/{close[0]}")
    return ("genuinely gone", "")


