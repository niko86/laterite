def parse_added_ranges(since_ref: str) -> dict[str, set[int]]:
    """WIKI-relative posix path -> set of line numbers added/modified in
    `git diff --unified=0 <since_ref>...HEAD -- ags-wiki`. Powers A5: a
    debt-check finding only fails the run if its (file, line) is in this
    map — everything else is grandfathered. `--unified=0` means each hunk
    is exactly its changed lines (no context), so a hunk's `+start,count`
    maps directly onto `count` consecutive new-file line numbers starting
    at `start`, regardless of how they interleave with removed lines
    (removed lines don't consume new-file line numbers)."""
    try:
        out = subprocess.run(
            [
                "git",
                "-C",
                str(REPO_ROOT),
                "diff",
                "--unified=0",
                f"{since_ref}...HEAD",
                "--",
                "ags-wiki",
            ],
            capture_output=True,
            text=True,
            check=True,
        )
    except (subprocess.CalledProcessError, FileNotFoundError) as e:
        print(
            f"--since {since_ref!r}: git diff failed ({e}); can't ratchet, aborting.",
            file=sys.stderr,
        )
        sys.exit(2)
    ranges: dict[str, set[int]] = {}
    cur_file: str | None = None
    hunk_re = re.compile(r"^@@ -\d+(?:,\d+)? \+(\d+)(?:,(\d+))? @@")
    for line in out.stdout.splitlines():
        if line.startswith("+++ "):
            path = line[4:]
            if path == "/dev/null":
                cur_file = None
                continue
            stripped = path[2:] if path.startswith(("a/", "b/")) else path
            try:
                cur_file = Path(stripped).relative_to("ags-wiki").as_posix()
            except ValueError:
                cur_file = None  # touched file outside ags-wiki/ — not lint's concern
            continue
        m = hunk_re.match(line)
        if m and cur_file is not None:
            start = int(m.group(1))
            count = int(m.group(2)) if m.group(2) is not None else 1
            if count > 0:
                ranges.setdefault(cur_file, set()).update(range(start, start + count))
    return ranges


ADDED_RANGES: dict[str, set[int]] = parse_added_ranges(SINCE_REF) if SINCE_REF else {}


def in_added_range(rel: str, line: int) -> bool:
    return line in ADDED_RANGES.get(rel, set())


def net_removed_citations(since_ref: str) -> list[str]:
    """Tier-3 (#23): `repo:` citations REMOVED by this diff and not re-added
    elsewhere in it — a signal the diff de-grounded a claim (deleted the ref)
    rather than repointing it. Report-only: a legitimately-deleted page removes
    its refs too, so this flags for a human look, it doesn't fail the run.
    log.md/index.md exempt (machine-maintained, same as the ratchet)."""
    try:
        out = subprocess.run(
            [
                "git",
                "-C",
                str(REPO_ROOT),
                "diff",
                f"{since_ref}...HEAD",
                "--",
                "ags-wiki",
            ],
            capture_output=True,
            text=True,
            check=True,
        )
    except (subprocess.CalledProcessError, FileNotFoundError):
        return []
    added, removed = set(), []
    cur = None
    for line in out.stdout.splitlines():
        if line.startswith("+++ "):
            path = line[6:] if line[4:].startswith("b/") else line[4:]
            cur = path
            continue
        if line.startswith("+") and not line.startswith("+++"):
            added |= {m.group(0) for m in REPO_REF.finditer(line)}
        elif line.startswith("-") and not line.startswith("---"):
            if cur and Path(cur).name in {"log.md", "index.md"}:  # machine-maintained
                continue
            removed.extend((cur, m.group(0)) for m in REPO_REF.finditer(line))
    return [f"{f} -> {ref}" for f, ref in removed if ref not in added]


def strip_code(t: str) -> str:
    # drop fenced blocks then inline code so example [[links]] in
    # backticks (schema syntax docs) aren't treated as real links
    t = re.sub(r"```.*?```", "", t, flags=re.S)
    return re.sub(r"`[^`]*`", "", t)


