    for sm in re.finditer(r"\[!stale-risk\][^\n]*?as-of\s*(\d{4}-\d{2}-\d{2})", txt):
        asof = sm.group(1)
        block = callout_block(txt, sm.start())  # scope to THIS callout, not the file
        for rm in REPO_REF.finditer(block):
            rraw = rm.group(1)
            if is_placeholder(rraw):
                continue
            ok_ref, rused = resolve_ref(rraw)
            if not ok_ref:
                continue
            d = git_last_date(rused)
            if d and d > asof:
                stale_risk_hits.append(
                    f"{rel} (as-of {asof}) -> repo:{rused} changed {d} "
                    f"(cited file moved after the snapshot)"
                )

    # A9 — ext: allowlist check (same trailing-punctuation tolerance as
    # resolve_ref, since ext: refs land in quoted frontmatter too)
    for m in EXT_REF.finditer(txt):
        raw = m.group(1)
        if is_placeholder(raw):
            continue
        clean = raw
        while clean and clean[-1] in TRAILING_PUNCT:
            clean = clean[:-1]
        repo_id, _ext_path = parse_ext_ref(clean)
        ln = line_at(txt, m.start())
        if repo_id in EXT_ALLOWLIST:
            ext_refs.append(f"{rel}:{ln} -> ext:{raw}")
        else:
            bad_ext_refs.append(
                f"{rel}:{ln} -> ext:{raw}  (repo-id '{repo_id}' not in EXT_ALLOWLIST)"
            )

    # A11 — build this page's line -> exempted-terms map before scanning
    # for retired terms, and flag any marker that LOOKS like an exemption
    # attempt but isn't well-formed.
    line_exemptions: dict[int, object] = {}  # int -> "ALL" | set[str]
    for lm in HISTORICAL_ATTEMPT.finditer(txt):
        ln = line_at(txt, lm.start())
        seg = lm.group(0)
        smatch = HISTORICAL_SPECIFIC.fullmatch(seg)
        if HISTORICAL_GENERIC.fullmatch(seg):
            line_exemptions[ln] = "ALL"
        elif smatch and smatch.group(1) in RETIRED_TERMS:
            existing = line_exemptions.get(ln)
            if existing == "ALL":
                pass
            elif isinstance(existing, set):
                existing.add(smatch.group(1))
            else:
                line_exemptions[ln] = {smatch.group(1)}
        else:
            bad_term = smatch.group(1) if smatch else None
            reason = (
                f"'{bad_term}' is not in RETIRED_TERMS"
                if bad_term
                else "not `historical` or `retired: <term>`"
            )
            malformed_markers.append(f"{rel}:{ln} -> {seg!r} ({reason})")

    for term, pat in RETIRED_PATTERNS:
        for m in pat.finditer(txt):
            ln = line_at(txt, m.start())
            exemption = line_exemptions.get(ln)
            if exemption == "ALL" or (isinstance(exemption, set) and term in exemption):
                exempted_counts[term] += 1
                continue
            start, end = max(0, m.start() - 30), min(len(txt), m.end() + 30)
            snippet = txt[start:end].replace("\n", " ")
            retired_counts[term] += 1
            retired_hits.append(
                {"file": rel, "line": ln, "term": term, "snippet": snippet}
            )

