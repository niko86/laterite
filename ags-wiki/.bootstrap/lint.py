# A1/A3 — repo: dead-ref scan, with a grammar that gets the citation forms
# right BEFORE anything here can fail the build:
#   repo:path/file.rs:352            (line suffix)
#   repo:.../mod.rs::run_all         (symbol suffix)
#   repo:OBSERVATIONS.md#o-33        (anchor suffix)
#   repo:rust-packages/*/build.rs    (glob — "exists" if it matches ≥1 path)
#   repo:.../{python,node,cli}/      (brace alternation — same ≥1-match rule)
# CRITICAL: this scans the RAW page text (`txt`, not `strip_code(txt)`).
# ~36% of repo: refs are wrapped in backticks in this vault; stripping code
# spans first — the way the wikilink check above does — would silently
# skip exactly the refs written in the citation grammar's own recommended
# form (AGS-WIKI.md §1). That blind spot is the whole reason this check
# exists, so it can't inherit strip_code()'s behaviour.
# ---------------------------------------------------------------------------
def anchor_problem(raw: str, resolved: str) -> str | None:
    """Tier-3 symbol/line-anchor validation (report-only) — for a `repo:` ref
    whose FILE exists, check its `:NN`/`:NN-MM` line suffix is in range and its
    `::symbol` suffix actually appears in the file. Skips globs/dirs (no single
    file to check) and `#anchor` (markdown, not validated here). Deliberately
    lenient: a symbol only has to appear as a word somewhere in the file, so a
    rename is flagged but a moved-within-file symbol is not (refactor noise)."""
    fp = REPO_ROOT / resolved
    if not fp.is_file():
        return None
    r = raw
    while r and r[-1] in TRAILING_PUNCT:
        r = r[:-1]
    m = re.search(r"::([A-Za-z_][A-Za-z0-9_]*)$", r)
    if m:
        try:
            text = fp.read_text(encoding="utf-8", errors="replace")
        except OSError:
            return None
        if re.search(rf"\b{re.escape(m.group(1))}\b", text) is None:
            return f"symbol '{m.group(1)}' not found in {resolved}"
        return None
    m = re.search(r":(\d+)(?:-(\d+))?$", r)
    if m:
        try:
            n = sum(1 for _ in fp.open("rb"))
        except OSError:
            return None
        hi = int(m.group(2) or m.group(1))
        if hi > n:
            return f"line {hi} out of range (file has {n} lines): {resolved}"
    return None


def git_last_date(path: str) -> str | None:
    """`git log -1 --format=%cs` (committer date, YYYY-MM-DD) for a repo path,
    or None if untracked / not a file. Powers the stale-risk freshness check."""
    fp = REPO_ROOT / path
    if not fp.is_file():
        return None
    try:
        out = subprocess.run(
            ["git", "-C", str(REPO_ROOT), "log", "-1", "--format=%cs", "--", path],
            capture_output=True,
            text=True,
            check=True,
        )
    except (subprocess.CalledProcessError, FileNotFoundError):
        return None
    return out.stdout.strip() or None


def callout_block(txt: str, pos: int) -> str:
    """The contiguous `>`-quoted Obsidian callout containing byte `pos` (the
    `[!stale-risk]` match), or "" if `pos` isn't on a callout line.

    The `as-of DATE` promise vouches only for citations *inside its own callout*,
    so the freshness scan must be scoped to this block — never the whole file.
    Scanning the file flooded the report: log.md carries one such callout (plus,
    ironically, this convention quoted verbatim in a `- notes:` line) alongside
    hundreds of unrelated `repo:` refs across its history, each spuriously
    "stale". A prose mention that isn't a real `> ` callout yields "" and is
    ignored."""
    ls = txt.rfind("\n", 0, pos) + 1  # start of the line the match sits on
    if not txt.startswith(">", ls):  # not a callout line → not a callout
        return ""
    end = ls
    while end < len(txt):
        nl = txt.find("\n", end)
        stop = nl if nl != -1 else len(txt)
        if not txt.startswith(">", end):
            break
        end = stop + 1 if nl != -1 else stop
    return txt[ls:end]


def is_placeholder(raw: str) -> bool:
    # AGS-WIKI.md's own citation-grammar examples use literal "..." /
    # "…" as fill-in-the-blank markers (§1's "repo symbol" example, the
    # §9 log.md grammar line) — content-based, not a per-file exemption,
    # so a real dead ref elsewhere with an actual ellipsis-free path (e.g.
    # the ags5_dictionary.json rename below) still gets reported.
    return "..." in raw or "…" in raw


def _git_tracked_files() -> list[str]:
    try:
        out = subprocess.run(
            ["git", "-C", str(REPO_ROOT), "ls-files"],
            capture_output=True,
            text=True,
            check=True,
        )
        return [ln for ln in out.stdout.splitlines() if ln]
    except (subprocess.CalledProcessError, FileNotFoundError):
        return []


