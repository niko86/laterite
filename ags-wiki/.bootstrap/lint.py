# B1 — frontmatter schema, single-sourced from templates/ (never hand-
# duplicated here — the #31/D5 audit finding this plan explicitly guards
# against). Each `_template-<class>.md`'s own frontmatter block IS the
# required-key set for its `type:` — read it at lint-run time so a template
# edit (a field added/renamed) updates the check automatically, with no
# second copy to fall out of sync. Report-only: a page missing a key the
# template promises is real debt, but "well-formed per the vault's
# conventions" is being defined for the first time here (no #12-documented
# schema existed before Phase B) — see the AGS-WIKI.md §12 writeup for the
# judgment calls this makes.
# ---------------------------------------------------------------------------
def top_level_keys(fm: str) -> set[str]:
    # column-0 `key:` lines only — nested keys (e.g. `repo_refs:\n  root:`)
    # are indented and correctly excluded from the top-level required set.
    return set(re.findall(r"^([A-Za-z_][A-Za-z0-9_]*):", fm, re.M))


def line_at(text: str, pos: int) -> int:
    return text.count("\n", 0, pos) + 1


def fm_list(fm: str, key: str) -> list[str]:
    """A frontmatter `key:` value as a list of bare stems. Accepts both
    `key: [a, b/c]` and a single bare `key: a`; `key:` / `key: []` -> [].
    Path-qualified entries (`folder/stem`) reduce to the stem, matching the
    wikilink/related handling elsewhere in this file."""
    m = re.search(rf"^{re.escape(key)}:\s*(.*?)\s*$", fm, re.M)
    if not m:
        return []
    raw = m.group(1).strip()
    if raw.startswith("[") and raw.endswith("]"):
        raw = raw[1:-1]
    return [x.strip().split("/")[-1] for x in raw.split(",") if x.strip()]


# D4 (wiki-reliability plan): a superseded page must carry a read-time
# tombstone — a callout admonition (`> [!...]`) whose block text names the
# supersession/retirement — so a page for a deleted package can't sit indexed
# among live pages with no visible signal it's dead. Matches both in-vault
# styles: `> [!note] Retired package…` (single line) and the multi-line
# `> [!note]` / `> **Superseded … by [[…]]**` decision form.
_CALLOUT_BLOCK = re.compile(r"^> \[!\w+\].*(?:\n>.*)*", re.M)


def has_tombstone(body: str) -> bool:
    for m in _CALLOUT_BLOCK.finditer(body):
        if re.search(r"supersed|retired", m.group(0), re.I):
            return True
    return False


