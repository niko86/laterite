def _workspace_crates() -> set[str]:
    """Every crate in the Rust workspace — the SSOT the crate-map graph must name."""
    ct = REPO_ROOT / "rust-packages" / "Cargo.toml"
    if not ct.exists():
        return set()
    return set(tomllib.loads(ct.read_text()).get("workspace", {}).get("members", []))


def _group_codes() -> set[str]:
    """A *documented* AGS group: in the AGS4 union dictionary OR carrying a wiki
    group page. The vault has pages for AGS-L / concept groups (TREL, CONL, TRIL,
    …) that are not in the shipped AGS4 union, so an erDiagram may legitimately
    name them — the check is 'documented somewhere', not 'in the dictionary'
    (which would mis-flag the concept groups)."""
    dj = (
        REPO_ROOT
        / "rust-packages"
        / "laterite-ags4-reference"
        / "data"
        / "ags_dictionary.json"
    )
    codes = set(json.loads(dj.read_text())["groups"]) if dj.exists() else set()
    return codes | {p.stem for p in (WIKI / "groups").glob("*.md")}


def _erd_entities(block: str) -> set[str]:
    """The 4-char group codes named as entities in an `erDiagram` block — the
    relationship endpoints (`A ||--o{ B`) and entity headers (`A {`), NOT the
    `<type> <heading>` attribute lines inside the `{ }` (those aren't groups)."""
    ents: set[str] = set()
    for line in block.splitlines():
        s = line.strip()
        m = re.match(r"([A-Z][A-Z0-9]{3})\s*\|\|[-o{}]*\s*([A-Z][A-Z0-9]{3})", s)
        if m:
            ents.update(m.groups())
            continue
        m = re.match(r"([A-Z][A-Z0-9]{3})\s*\{", s)
        if m:
            ents.add(m.group(1))
    return ents


# C5 long-term (wiki-reliability plan #10): edge-correctness for the crate-map
# graph. Node-completeness (every workspace crate is a node) is already gated
# above; this gates the *edges*. The graph is a curated `flowchart LR` layering
# view, NOT a strict dependency DAG (its arrow direction is deliberately loose —
# `types-->core` reads leaf→consumer, `core-->parse` reads consumer→leaf), and
# it may omit edges for readability — so completeness/direction can't be gated.
# What CAN: every edge it *draws* must connect two crates with a real Cargo
# coupling in *either* direction. A phantom edge between two uncoupled crates
# (a stale arrow left after a dependency was dropped) is caught; the diagram
# stays free to simplify.
def _crate_deps() -> dict[str, set[str]]:
    """crate name -> its workspace-member dependency names (all dep sections)."""
    rp = REPO_ROOT / "rust-packages"
    ct = rp / "Cargo.toml"
    if not ct.exists():
        return {}
    members = tomllib.loads(ct.read_text()).get("workspace", {}).get("members", [])
    out: dict[str, set[str]] = {}
    for m in members:
        mct = rp / m / "Cargo.toml"
        if not mct.exists():
            continue
        d = tomllib.loads(mct.read_text())
        nm = d.get("package", {}).get("name")
        if not nm:
            continue
        deps: set[str] = set()
        for sec in ("dependencies", "build-dependencies", "dev-dependencies"):
            deps |= set(d.get(sec, {}).keys())
        out[nm] = deps
    return out


def _crate_map_edges() -> list[tuple[str, str]]:
    """(name, name) for each `A --> B` in crate-map.md's graph, resolving node
    ids through their `id[crate-name]` / `id[crate-name<br/>alias]` labels."""
    if not CRATE_MAP.exists():
        return []
    block = "\n".join(
        re.findall(r"```mermaid\n(.*?)```", CRATE_MAP.read_text(), re.DOTALL)
    )
    id2name = {
        m.group(1): m.group(2)
        for m in re.finditer(r"(\w+)\[([a-z0-9-]+)(?:<br/>[^\]]*)?\]", block)
    }
    return [
        (id2name.get(a, a), id2name.get(b, b))
        for a, b in re.findall(r"(\w+)\s*-->\s*(\w+)", block)
    ]


# Reliquary self-check (wiki-reliability): the "Machine-checked register" table
# in design/reliquary.md must stay true to the tree, so the register can't rot
# into a list of claims nobody verifies. Each gated row carries a `path::token`
# Verify anchor; a `removed` relic's token must be ABSENT at that path, a still-
# inventoried one (spotted/keep/mitigated) must be PRESENT. So a relic can't be
# marked removed while its code lingers, nor silently vanish while still listed
# present. Rows with Verify `—` are display-only (the legacy narrative register
# above it is not machine-checked). Token match is a literal substring scoped to
# the one file — precise enough given a hand-picked declaration-fragment token.
_RELIQUARY = WIKI / "design" / "reliquary.md"
_RELIQUARY_PRESENT = {"spotted", "keep", "mitigated"}
_RELIQUARY_ABSENT = {"removed"}


def _machine_register_rows(txt: str) -> list[dict]:
    """Rows of the `## Machine-checked register` table: {symbol, verify, status}.
    Columns are Symbol | Verify | Axis | Status | Removed-in | Evidence."""
    rows: list[dict] = []
    in_section = False
    for line in txt.splitlines():
        if line.startswith("## "):
            in_section = "machine-checked register" in line.lower()
            continue
        if not in_section:
            continue
        s = line.strip()
        if not s.startswith("|"):
            continue
        cells = [re.sub(r"[`*]", "", c).strip() for c in s.strip("|").split("|")]
        if len(cells) < 4 or cells[0].lower() == "symbol":
            continue
        if set("".join(cells)) <= set("-: "):  # header separator row
            continue
        rows.append(
            {"symbol": cells[0], "verify": cells[1], "status": cells[3].lower()}
        )
    return rows


def _reliquary_violations() -> list[str]:
    if not _RELIQUARY.exists():
        return []
    out: list[str] = []
    for r in _machine_register_rows(_RELIQUARY.read_text(encoding="utf-8")):
        verify, status, sym = r["verify"], r["status"], r["symbol"]
        if verify in ("", "—", "-"):
            continue
        if "::" not in verify:
            out.append(f"`{sym}`: malformed Verify {verify!r} (want `path::token`)")
            continue
        rel, token = verify.split("::", 1)
        target = REPO_ROOT / rel
        present = target.exists() and token in target.read_text(
            encoding="utf-8", errors="replace"
        )
        if status in _RELIQUARY_ABSENT and present:
            out.append(
                f"`{sym}` marked {status} but token `{token}` still present in {rel}"
            )
        elif status in _RELIQUARY_PRESENT and not present:
            out.append(
                f"`{sym}` marked {status} but token `{token}` not found in {rel} (stale row)"
            )
        elif status not in _RELIQUARY_PRESENT | _RELIQUARY_ABSENT:
            out.append(f"`{sym}` has unknown status {status!r}")
    return out


