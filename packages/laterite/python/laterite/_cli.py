def _plain(file: str, findings: list[dict], n: int) -> str:
    if n == 0:
        return f"{file}: clean (0 findings)\n"
    w = [4, 4, 5, 11]
    rows = []
    for f in findings:
        short = f["rule"].removeprefix("AGS Format Rule ")
        line = "-" if f["line"] is None else str(f["line"])
        cells = [short, line, f["group"], f["desc"]]
        for i, c in enumerate(cells):
            w[i] = max(w[i], len(c))
        rows.append(cells)
    head = ["Rule", "Line", "Group", "Description"]
    out = [f"{file}: {n} finding(s)"]
    out.append(" | ".join(h.ljust(w[i]) for i, h in enumerate(head)))
    out.append("-+-".join("-" * w[i] for i in range(4)))
    out.extend(" | ".join(r[i].ljust(w[i]) for i in range(4)) for r in rows)
    return "\n".join(out) + "\n"


def _engine(args: argparse.Namespace) -> dict:
    """A full rules pass — the `run_check` verdict dict every renderer below reads."""
    return _native.run_check(
        path=args.file,
        dict_version=args.dict_version,
        include_warnings=not args.no_warnings,
        include_fyi=args.show_fyi,
        check_files=args.check_files,
        encoding=args.encoding,
        dict_path=args.dict,
        dict_replace=args.dict_replace,
    )


def _pin(args: argparse.Namespace) -> Edition | None:
    """The edition pin as the *library* spells it: an edition, or `None` for none.

    `--dict-version` defaults to the string `"auto"`, which is the CLI's sentinel for
    "no pin" — the native `parse_dv` maps `"auto"` to `None`. The library has no such
    sentinel, and handing it straight through does not fail loudly: it makes the
    request look like a FORCED edition, so a certificate minted without one stops
    covering it and every `--index` skip quietly disarms. Which is exactly what this
    flag did the first time it ran.
    """
    dv = args.dict_version
    if dv in (None, "", "auto"):
        return None
    # argparse already enforced `choices=_DICT_CHOICES`, which IS the bundled edition
    # set — so the string is one of them by construction, and the cast states what the
    # parser has already guaranteed.
    return cast("Edition", dv)


def _with_cert(args: argparse.Namespace) -> dict:
    """`--index <cert>`: give a `.ags.idx` certificate first refusal at the verdict.

    The cert POLICY is the library's — :func:`laterite.read` fails fast when the
    cert's bytes don't match the file, and ``.validate()`` decides whether the cert
    may stand in for a rules pass — not a second hand-written copy here. The CLI
    adds only the binary's recovery posture: a cert that cannot be trusted is a
    NOTE, not an error. Re-validating is always safe; refusing to run because a
    cert went stale would not be.

    Imported lazily on purpose. This module is otherwise native-only, and pulling
    polars + duckdb in would tax every `lat validate` for a flag almost nobody
    passes.
    """
    from . import Ags4Error, StaleCertError, read

    try:
        handle = read(args.file, index=args.index, encoding=args.encoding)
    except StaleCertError as e:
        print(f"note: --index not used ({e}); running the full check", file=sys.stderr)
        return _engine(args)
    except Ags4Error as e:
        # Un-validatable input (missing, not AGS4, bad edition) — the same
        # `{ok: False}` shape `run_check` returns, so the caller is none the wiser.
        return {"ok": False, "error": str(e), "exit_code": e.exit_code}

    try:
        report = handle.validate(
            dict_version=_pin(args),
            warnings=not args.no_warnings,
            fyi=args.show_fyi,
            check_files=args.check_files,
            dictionary=args.dict,
            dict_replace=args.dict_replace,
        ).report
    except Ags4Error as e:
        return {"ok": False, "error": str(e), "exit_code": e.exit_code}

    if report.certified:
        # "rule engine skipped", not "file not checked": a world check (Rule 20's on-disk
        # half) runs even on a certified read — a certificate cannot vouch for a directory.
        print(
            "note: certified clean by the .ags.idx certificate — rule engine skipped",
            file=sys.stderr,
        )
    return report._r


def _run_validate(args: argparse.Namespace) -> int:
    r = _with_cert(args) if args.index else _engine(args)
    if not r.get("ok"):
        print(f"error: {r.get('error')}", file=sys.stderr)
        return int(r.get("exit_code", 5))

    n = r["count"]
    code = r["exit_code"]

    if args.json:
        active = r["json"] + "\n"
    elif args.ndjson:
        active = r["ndjson"]
    else:
        active = _plain(r["file"], r["findings"], n)

    if args.json_out:
        with Path(args.json_out).open("w", encoding="utf-8", newline="") as fh:
            fh.write(r["json"] + "\n")
        sys.stdout.write(
            _plain(r["file"], r["findings"], n)
        )  # tee: plain still to stdout
        return code

    if args.out:
        with Path(args.out).open("w", encoding="utf-8", newline="") as fh:
            fh.write(active)
        print(
            f"{r['file']}: {n} finding(s)" if n else f"{r['file']}: clean (0 findings)"
        )
        return code

    sys.stdout.write(active)
    return code


def _run_fix(args: argparse.Namespace) -> int:
    """`lat fix`: mechanically repair the file. Faithful to the Rust `fix`
    (sibling `<file>.fixed.ags` by default; `--in-place` / `--fix-out` redirect).
    Exit 0 clean · 1 residual · 3/4/5 read/parse/dict errors."""
    import json
    from pathlib import Path

    if args.in_place and args.fix_out:
        print("error: --in-place and --fix-out are mutually exclusive", file=sys.stderr)
        return 5

    r = _native.fix_file(
        path=args.file,
        dict_version=args.dict_version,
        include_risky=args.risky,
        encoding=args.encoding,
        dict_path=args.dict,
        dict_replace=args.dict_replace,
    )
    if not r.get("ok"):
        print(f"error: {r.get('error')}", file=sys.stderr)
        return int(r.get("exit_code", 5))

    src = Path(args.file)
    if args.in_place:
        dest = src
    elif args.fix_out:
        dest = Path(args.fix_out)
    elif src.suffix:
        dest = src.with_name(f"{src.stem}.fixed{src.suffix}")
    else:
        dest = src.with_name(f"{src.name}.fixed")
    try:
        dest.write_bytes(r["fixed"])
    except OSError as e:
        print(f"error: writing {dest}: {e}", file=sys.stderr)
        return 3

    by_rule = json.loads(r["findings_json"])
    n_residual = sum(len(v) for v in by_rule.values())

    # --json: the machine-readable report replaces the human summary (#545). Same
    # shape as the native `lat fix --json` — `applied` is the native `fix_file`'s
    # `{kind, label, rule, line, risk}` ledger verbatim. Exit unchanged (0/1).
    if args.json:
        # `risky_available` is human-only: the Node FixReport has no risky-count to
        # mirror, so the machine report omits it to stay identical across launchers.
        report = {
            "file": str(args.file),
            "dest": str(dest),
            "applied": r["applied"],
            "residual": n_residual,
        }
        # ensure_ascii=False: a fix label carries the reformat arrow (`"10.5" → "10.50"`,
        # Rule 8), and Python's json.dumps ASCII-escapes it to `→` while the native
        # serde_json and npx JSON.stringify emit the raw UTF-8 char. Without this the
        # three launchers' `fix --json` diverge on an ordinary DP-precision fix (#545).
        print(json.dumps(report, indent=2, ensure_ascii=False))
        return 0 if n_residual == 0 else 1

    kinds = sorted({a["kind"] for a in r["applied"]})
    n_applied = r["fixes_applied"]
    if n_applied == 0:
        print(f"no fixes applicable → {dest}")
    else:
        print(f"applied {n_applied} fix(es) [{', '.join(kinds)}] → {dest}")

    if n_residual == 0:
        print(f"{dest}: clean (0 findings)")
        return 0
    print(f"{dest}: {n_residual} finding(s) remain (not mechanically fixable)")
    return 1


def _list_rules(as_json: bool) -> int:
    """`lat rules`: print the rule catalogue and exit 0. `--json` emits the raw
    gated `rules_meta.json` (byte-faithful to the Rust binary); otherwise a
    compact Rule | Title | Severity | Fix? table."""
    raw = _native.list_rules()
    if as_json:
        print(raw)
        return 0
    import json

    rules = json.loads(raw)["rules"]
    w = [4, 5, 8, 4]
    rows = []
    for r in rules:
        cells = [
            r["rule"],
            r.get("title", ""),
            r.get("severity", ""),
            "yes" if r.get("fixable") else "",
        ]
        for i, c in enumerate(cells):
            w[i] = max(w[i], len(c))
        rows.append(cells)
    head = ["Rule", "Title", "Severity", "Fix?"]
    out = [" | ".join(h.ljust(w[i]) for i, h in enumerate(head)).rstrip()]
    out.append("-+-".join("-" * w[i] for i in range(4)))
    out.extend(" | ".join(r[i].ljust(w[i]) for i in range(4)).rstrip() for r in rows)
    print("\n".join(out))
    return 0


def _run_diff(args: argparse.Namespace) -> int:
    """`lat diff <a> <b>`: the KEY-aware/type-aware revision delta. Faithful to
    the Rust `diff`: a per-group summary (or the full delta with `--json`)."""
    import json
    from pathlib import Path

    try:
        a = Path(args.file).read_bytes()
        b = Path(args.other).read_bytes()
    except OSError as e:
        print(f"error: {e}", file=sys.stderr)
        return 3
    r = _native.diff_files(a, b, dict_version=args.dict_version, encoding=args.encoding)
    if not r.get("ok"):
        print(f"error: {r.get('error')}", file=sys.stderr)
        return int(r.get("exit_code", 5))
    delta = json.loads(r["delta_json"])
    if args.json:
        print(json.dumps(delta, indent=2))
        return 0
    print(f"{args.file} → {args.other}")
    for g in delta["groups"]:
        print(f"  {g['code']:<6} +{g['added']} -{g['removed']} ~{g['changed']}")
    if delta["groups_added"]:
        print(f"  groups added:   {', '.join(delta['groups_added'])}")
    if delta["groups_removed"]:
        print(f"  groups removed: {', '.join(delta['groups_removed'])}")
    print(
        f"  total: +{delta['total_added']} added · "
        f"−{delta['total_removed']} removed · ~{delta['total_changed']} changed"
    )
    return 0


def _tran_from_args(args: argparse.Namespace) -> TranStamp | None:
    """Fold the five ``--tran-*`` flags into the one object the library takes.

    CLI flags are irreducibly five independent optionals, so the flattening has
    to happen somewhere. Doing it here — and refusing a partial set with the
    library's own vocabulary — keeps "all five or none" answered in one place.
    """
    parts = {
        "issue": args.tran_issue,
        "date": args.tran_date,
        "producer": args.tran_producer,
        "recipient": args.tran_recipient,
        "status": args.tran_status,
    }
    missing = [k for k, v in parts.items() if not (v or "").strip()]
    if len(missing) == 5:
        return None  # nothing stated: no merge-TRAN, and that is reported
    if missing:
        raise SystemExit(
            f"error: incomplete TRAN: missing {', '.join(missing)}. All five are "
            "REQUIRED headings (TRAN_ISNO/DATE/PROD/RECV/STAT), so a partial "
            "stamp would emit a TRAN that fails Rule 10b. Supply all five, or "
            "none to omit TRAN.\n"
            "       flags: --tran-issue --tran-date --tran-producer "
            "--tran-recipient --tran-status"
        )
    from . import TranStamp as _TranStamp

    return _TranStamp(**parts)


def _run_merge(args: argparse.Namespace) -> int:
    """`lat merge <files...> --out <merged.ags>` — reconcile N deliveries into one.

    Faithful to the Rust `merge`: argument order is the authority (the LAST file
    wins a KEY conflict), `--out` is required (never a silent default over an
    input), and the `--json` summary carries the same `{out, bytes, warnings,
    revisions}` shape. Exit 0 merged · 3 read/write · 4 parse · 5 bad args ·
    6 an irreconcilable TYPE/UNIT clash.

    This verb reached the native binary in #494 and did not reach this launcher
    until the surface census caught the omission — the first bug that gate found.
    """
    from pathlib import Path

    import laterite

    if len(args.files) < 2:
        print("error: merge needs at least two files", file=sys.stderr)
        return 5
    for f in args.files:
        if not Path(f).exists():
            print(f"error: {f}: not found", file=sys.stderr)
            return 3

    dv = None if args.dict_version == "auto" else args.dict_version
    try:
        res = laterite.merge(
            *args.files,
            on_type_clash=args.on_type_clash,
            dict_version=dv,
            encoding=args.encoding,
            tran=_tran_from_args(args),
        )
    except laterite.MergeConflictError as e:
        # The library message already carries the full guidance (which modes settle
        # this clash, and — for a UNIT clash — that none of them do, #501), so we do
        # NOT append CLI hints on top: that doubled the advice.
        #
        # It is still not byte-faithful to the Rust `lat merge`, which prints
        # `error: TYPE conflict in <G>.<H>: ...` plus two `hint:` lines in CLI
        # register (`--on-type-clash promote`), where this prints the library's
        # register (`on_type_clash=promote`). Closing that needs structured fields on
        # MergeConflictError (it carries only a message + exit_code today) so this
        # launcher can render the CLI's own wording from the same facts. Tracked with
        # the message-parity findings the value runner is built to catch — not fudged
        # here by re-deriving a second error taxonomy from string matching.
        print(f"error: {e}", file=sys.stderr)
        return 6
    except Exception as e:
        print(f"error: {e}", file=sys.stderr)
        return 4

    try:
        Path(args.out).write_bytes(res.bytes)
    except OSError as e:
        print(f"error: writing {args.out}: {e}", file=sys.stderr)
        return 3

    if args.json:
        print(
            json.dumps(
                {
                    "out": args.out,
                    "bytes": len(res.bytes),
                    "warnings": res.warnings,
                    "revisions": res.revisions,
                },
                indent=2,
            )
        )
        return 0

    print(f"merged {len(args.files)} files → {args.out} ({len(res.bytes)} bytes)")
    for w in res.warnings:
        print(f"  warning [{w['kind']}]: {w['message']}")
    if res.revisions:
        print(f"  {len(res.revisions)} row revision(s):")
        for r in res.revisions:
            print(
                f"    {r['group']} {r['key']}: changed {r['changed']} "
                f"(from file[{r['winner_file']}])"
            )
    return 0


def _run_certify(args: argparse.Namespace) -> int:
    """`lat certify <file>`: mint the `.ags.idx` for an error-clean file.

    This function used to be the FIFTH place in the codebase that decided what a
    certificate may attest, and it decided differently from the other four: it gated on
    `report.is_valid`, which is zero findings of ANY tier — so this launcher refused to
    certify an error-clean file that carried a single warning, while the native `lat`
    binary happily minted one for the same bytes. Three launchers, one contract, two
    behaviours.

    It no longer decides anything. `certify()` runs the validation itself and refuses a
    file with errors, which is the one rule there has ever been."""
    from . import Ags4Error, read

    dv = None if args.dict_version == "auto" else args.dict_version
    ckw = {"dictionary": args.dict, "dict_replace": args.dict_replace}
    try:
        handle = read(args.file, encoding=args.encoding)
        dest = (
            handle.certify(args.out, dict_version=dv, **ckw)
            if args.out
            else handle.certify(dict_version=dv, **ckw)
        )
    except FileNotFoundError:
        print(f"error: {args.file}: not found", file=sys.stderr)
        return 3
    except Ags4Error as e:
        # An error-carrying file is refused by the mint, in the mint's own words.
        if "cannot certify" in str(e):
            print(f"{e} (run `lat validate {args.file}` to see them)", file=sys.stderr)
            return 1
        print(f"error: {e}", file=sys.stderr)
        return e.exit_code
    except Exception as e:
        print(f"error: {e}", file=sys.stderr)
        return 4
    print(f"certificate written to {dest}")
    return 0


def _emit(body: str, out: str | None) -> int:
    if out:
        with Path(out).open("w", encoding="utf-8", newline="") as fh:
            fh.write(body)
        print(f"note: written to {out}", file=sys.stderr)
    else:
        sys.stdout.write(body)
    return 0


""" `read`'s CSV/JSON rendering is NOT done here: `_laterite_native`'s
`render_read_csv` / `render_read_json` call core's single writers, the same ones
the `lat` binary and Node use. This module used to hand-port RFC-4180 quoting
and reach for Python's `json.dumps` while the binary used `serde_json` and Node
used `JSON.stringify` — three libraries held byte-identical by discipline, with
no gate on `read` output (#530). """


def _read_table(headings: list[str], rows: list[list[str]]) -> str:
    """A plain aligned table for `lat read <group>` — the human view (the Rust
    binary renders its own comfy-table box grid; only --json/--csv are byte-coherent)."""
    w = [len(h) for h in headings]
    for row in rows:
        for i, c in enumerate(row):
            w[i] = max(w[i], len(c))
    lines = [" | ".join(h.ljust(w[i]) for i, h in enumerate(headings)).rstrip()]
    lines.append("-+-".join("-" * w[i] for i in range(len(headings))))
    lines.extend(
        " | ".join(row[i].ljust(w[i]) for i in range(len(headings))).rstrip()
        for row in rows
    )
    return "\n".join(lines) + "\n"


def _run_read(args: argparse.Namespace) -> int:
    """`lat read <file> [group]` — list the file's group codes, or dump a group
    as a table / CSV / JSON. Raw file cells via the native read codec, so the
    Rust binary and this CLI agree byte-for-byte on the group listing and on
    `read --json` / `--csv` (the human --table is each surface's own — #430 PR 2)."""
    import json as _json
    from pathlib import Path

    if not Path(args.file).exists():
        print(f"error: {args.file}: not found", file=sys.stderr)
        return 3
    try:
        raw = _native.read_groups_raw(args.file, args.recover_duplicate_headings)
    except Exception as e:
        print(f"error: {e}", file=sys.stderr)
        return 4

    order = raw["order"]
    if args.group is None:
        if not order:
            print("note: no groups in the file", file=sys.stderr)
            return 0
        body = (
            _json.dumps(order, indent=2, ensure_ascii=False) + "\n"
            if args.json
            else "\n".join(order) + "\n"
        )
        return _emit(body, args.out)

    if args.group not in raw["groups"]:
        present = ", ".join(order) or "none"
        print(
            f"error: group {args.group!r} not found in {args.file} (present: {present})",
            file=sys.stderr,
        )
        return 4

    g = raw["groups"][args.group]
    headings, rows = g["headings"], g["rows"]
    if args.json:
        body = _native.render_read_json(headings, rows)
    elif args.csv:
        body = _native.render_read_csv(headings, rows)
    else:
        # The table stays local — it is a presentation choice, not a data format.
        body = _read_table(headings, rows)
    return _emit(body, args.out)


def _resolve_password(password_file: str | None, prompt: str) -> str:
    """Passphrase precedence — `--password-file` → `$LAT_TRANSPORT_PASSWORD` → an
    interactive prompt (never echoed). NEVER a `--password` flag: argv leaks into
    `ps` and shell history. Mirrors the Rust `lat`'s resolution exactly."""
    import os
    from pathlib import Path

    if password_file:
        return Path(password_file).read_text(encoding="utf-8").rstrip("\r\n")
    env = os.environ.get("LAT_TRANSPORT_PASSWORD")
    if env:
        return env
    import getpass

    return getpass.getpass(prompt)


