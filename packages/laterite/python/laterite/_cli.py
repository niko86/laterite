def _run_excel(args: argparse.Namespace) -> int:
    """`lat excel <in> <out>` — AGS4 ↔ Excel. Direction is inferred from the
    output extension (`.xlsx` ⇒ export, `.ags` ⇒ import), or forced with
    `--export` / `--import`. Mirrors the Rust `lat excel`."""
    from pathlib import Path

    import laterite

    if not Path(args.input).exists():
        print(f"error: {args.input}: not found", file=sys.stderr)
        return 3
    if args.export:
        export = True
    elif args.import_:
        export = False
    else:
        ext = Path(args.output).suffix.lower()
        if ext == ".xlsx":
            export = True
        elif ext == ".ags":
            export = False
        else:
            print(
                f"error: can't infer direction from output {args.output} — "
                "pass --export (→ .xlsx) or --import (→ .ags)",
                file=sys.stderr,
            )
            return 5
    try:
        if export:
            laterite.to_excel(args.input, args.output)
        else:
            laterite.from_excel(
                args.input,
                args.output,
                format_numeric_columns=not args.no_format_numeric,
            )
    except Exception as e:
        print(f"error: {e}", file=sys.stderr)
        return 6
    print(
        f"{'exported' if export else 'imported'} {args.input} → {args.output}",
        file=sys.stderr,
    )
    return 0


def _global_parent() -> argparse.ArgumentParser:
    # `--quiet` is the one genuinely cross-cutting flag, so it stays global (mirrors
    # the native `Cli`). `--json`/`--ndjson` moved onto each report-producing verb in
    # #545 — a verb that can't render JSON now rejects the flag instead of ignoring
    # it — so they are declared per-subparser below, not here.
    p = argparse.ArgumentParser(add_help=False)
    p.add_argument("--quiet", action="store_true")
    return p


def _dict_parent() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(add_help=False)
    p.add_argument("--dict-version", choices=_DICT_CHOICES, default="auto")
    p.add_argument("--dict")
    # (with --dict) treat the custom dictionary as a FULL REPLACEMENT — no base edition
    # contributes. Mirrors the native `DictArgs::dict_replace`; contradicts --dict-version
    # (the native/library reject the pair with exit 5). (#568)
    p.add_argument("--dict-replace", dest="dict_replace", action="store_true")
    p.add_argument("--encoding")
    return p


def _subcommands(p: argparse.ArgumentParser) -> tuple[str, ...]:
    """The verbs this launcher dispatches — asked of the PARSER, never a list.

    A second hand-written verb table is the failure the surface census exists to
    catch: it is what let `lat merge` ship in the native binary and silently miss
    this launcher. The parser is what actually parses argv, so it is the only
    honest answer to "what verbs are there".
    """
    subs = next(
        (a for a in p._actions if isinstance(a, argparse._SubParsersAction)), None
    )
    return tuple(subs.choices) if subs else ()


def _with_default_subcommand(argv: list[str], p: argparse.ArgumentParser) -> list[str]:
    """Splice `validate` in when the first non-flag token isn't a known subcommand
    — so `lat <file>` (and `lat <file> --json`) route to validate, mirroring the
    Rust argv pre-scan. Leading `-` tokens are valueless bools, so a run of them is
    skipped without consuming a value.

    Inserts `validate` at the FRONT (not before the file): since #545 moved
    `--json`/`--ndjson` onto the verbs, a leading `lat --json <file>` must become
    `lat validate --json <file>` so the flag lands after the verb that declares it
    (before, with the flags global, position was immaterial)."""
    verbs = _subcommands(p)
    for a in argv:
        if a.startswith("-"):
            continue
        if a not in verbs:
            return ["validate", *argv]
        return argv
    return argv


def _build_parser() -> argparse.ArgumentParser:
    """The uvx launcher's parser.

    Extracted from ``main`` so :func:`census` can REFLECT the very parser that
    parses the real command line, rather than describing it from a second list.
    That distinction is the whole point of the surface census: ``lat merge``
    shipped in the native binary (#494) and never reached this launcher, and no
    gate saw it, because every gate compared one hand-list against another.
    """
    gp, dp = _global_parent(), _dict_parent()
    p = argparse.ArgumentParser(prog="lat", add_help=False)
    sub = p.add_subparsers(dest="cmd")

    pv = sub.add_parser("validate", add_help=False, parents=[gp, dp])
    pv.add_argument("file")
    # `--json`/`--ndjson` are per-verb now (#545). validate is the only verb that
    # streams NDJSON; the json↔ndjson mutual exclusion is enforced in `main`.
    pv.add_argument("--json", action="store_true")
    pv.add_argument("--ndjson", action="store_true")
    pv.add_argument("--no-warnings", action="store_true")
    pv.add_argument("--show-fyi", action="store_true")
    pv.add_argument("--check-files", action="store_true")
    # The door this launcher never had. The binary and npx both take a `.ags.idx`
    # certificate here; uvx simply omitted the flag, so a script portable across the
    # three launchers was not — `--index` was an unknown-argument error on this one.
    # The flags census is what made that visible: every earlier gate compared VERB
    # names, and `validate` was present on all three.
    pv.add_argument("--index")
    pv.add_argument("--out")
    pv.add_argument("--json-out")

    prd = sub.add_parser("read", add_help=False, parents=[gp])
    prd.add_argument("file")
    prd.add_argument("group", nargs="?")
    prd.add_argument("--json", action="store_true")
    prd.add_argument("--csv", action="store_true")
    prd.add_argument("--out")
    # Mirrors the Rust binary's flag exactly — `lat read` must accept the same
    # surface on both, or the cross-surface output gate diverges.
    prd.add_argument("--recover-duplicate-headings", action="store_true")

    pf = sub.add_parser("fix", add_help=False, parents=[gp, dp])
    pf.add_argument("file")
    pf.add_argument("--json", action="store_true")
    pf.add_argument("--risky", action="store_true")
    pf.add_argument("--in-place", action="store_true")
    pf.add_argument("--fix-out")

    pdf = sub.add_parser("diff", add_help=False, parents=[gp, dp])
    pdf.add_argument("file")
    pdf.add_argument("other")
    pdf.add_argument("--json", action="store_true")

    pm = sub.add_parser("merge", add_help=False, parents=[gp, dp])
    pm.add_argument("files", nargs="+")
    pm.add_argument("--json", action="store_true")
    pm.add_argument("--out", required=True)
    pm.add_argument(
        "--on-type-clash", dest="on_type_clash", choices=_CLASH_CHOICES, default="error"
    )
    pm.add_argument("--tran-issue", dest="tran_issue")
    pm.add_argument("--tran-date", dest="tran_date")
    pm.add_argument("--tran-producer", dest="tran_producer")
    pm.add_argument("--tran-recipient", dest="tran_recipient")
    pm.add_argument("--tran-status", dest="tran_status")

    pc = sub.add_parser("certify", add_help=False, parents=[gp, dp])
    pc.add_argument("file")
    # `--check-files` was here (and on the binary). It recorded, in the certificate, that
    # Rule 20's on-disk half had run — and a later `validate --check-files --index` read
    # that record and skipped the check. Delete the FILE/ tree in between and the file
    # still reported clean. A certificate is a statement about bytes; the directory beside
    # them is not one. Use `lat validate --check-files`, which runs it live.
    pc.add_argument("--out")

    pr = sub.add_parser("rules", add_help=False, parents=[gp])
    pr.add_argument("--json", action="store_true")

    pk = sub.add_parser("pack", add_help=False, parents=[gp])
    pk.add_argument("input")
    pk.add_argument("output")
    pk.add_argument("--level", type=int, default=9)

    pup = sub.add_parser("unpack", add_help=False, parents=[gp])
    pup.add_argument("input")
    pup.add_argument("output")

    pl = sub.add_parser("lock", add_help=False, parents=[gp])
    pl.add_argument("input")
    pl.add_argument("output")
    pl.add_argument("--level", type=int, default=9)
    pl.add_argument("--log-n", dest="log_n", type=int, default=None)
    pl.add_argument("--password-file", dest="password_file")

    pul = sub.add_parser("unlock", add_help=False, parents=[gp])
    pul.add_argument("input")
    pul.add_argument("output")
    pul.add_argument("--password-file", dest="password_file")

    pe = sub.add_parser("excel", add_help=False, parents=[gp])
    pe.add_argument("input")
    pe.add_argument("output")
    _exdir = pe.add_mutually_exclusive_group()
    _exdir.add_argument("--export", action="store_true")
    _exdir.add_argument("--import", dest="import_", action="store_true")
    pe.add_argument(
        "--no-format-numeric", dest="no_format_numeric", action="store_true"
    )

    return p


def _arg_json(a: argparse.Action) -> dict:
    """One argparse action as the census's shared arg shape.

    `takes_value` is the load-bearing field — it is what says whether a flag eats the
    next token, and the three launchers are diffed on it. Positionals are reported as
    `<name>` (as clap does), so a launcher that forgets an argument entirely is still
    visible to the diff rather than simply absent from it.
    """
    if a.option_strings:
        name = max(a.option_strings, key=len)  # the long form
        takes_value = a.nargs != 0 and not isinstance(
            a, argparse._StoreTrueAction | argparse._StoreFalseAction
        )
    else:
        name = f"<{a.dest}>"
        takes_value = True
    return {
        "name": name,
        "takes_value": bool(takes_value),
        "required": bool(a.required),
        "values": sorted(a.choices) if a.choices else [],
    }


def census() -> dict:
    """This launcher's parser, as JSON — the shape `lat census` emits.

    Reflected from :func:`_build_parser`, never hand-listed. ``tools/gen_census.py``
    diffs this against the native binary (the authority).
    """
    p = _build_parser()
    subs = next(
        (a for a in p._actions if isinstance(a, argparse._SubParsersAction)), None
    )
    # argparse types `choices` as an untyped Iterable, but a _SubParsersAction's
    # choices values ARE the per-verb parsers — which is the whole point here: we
    # reflect each real parser rather than describing it from a list.
    choices = cast(
        "dict[str, argparse.ArgumentParser]", dict(subs.choices) if subs else {}
    )

    # The two launchers declare the same globals in opposite directions: clap hangs
    # `--json/--ndjson/--quiet` off the ROOT command, while argparse can only reach a
    # subcommand through `parents=[gp]`, which COPIES them into every verb. Reflecting
    # the shared parent is what lets the census subtract them back out and compare the
    # per-verb tables like for like — rather than reporting three phantom extra flags
    # on all twelve verbs.
    global_args = [_arg_json(a) for a in _global_parent()._actions]
    global_names = {a["name"] for a in global_args}
    global_args.sort(key=lambda d: d["name"])

    verbs = []
    for verb, sp in choices.items():
        args = [
            j for a in sp._actions if (j := _arg_json(a))["name"] not in global_names
        ]
        args.sort(key=lambda d: d["name"])
        verbs.append({"verb": verb, "args": args})
    verbs.sort(key=lambda d: d["verb"])
    return {
        # See CENSUS_VERSION in the Rust census — bumped when a TABLE is added, so a
        # launcher built before a table existed fails loudly rather than reporting it
        # empty (which would read as "no drift").
        "census_version": 5,
        "surface": "cli-uvx",
        "authority": False,
        "verbs": verbs,
        "global_args": global_args,
        "documented_verbs": list(_subcommands(p)),
        # The editions this launcher accepts for --dict-version, minus the "auto"
        # sentinel (which is not an edition). Derived, so it agrees with the native
        # binary by construction — and the census proves it rather than assuming it.
        "editions": [e for e in _DICT_CHOICES if e != "auto"],
        "fallback_edition": _native.registry_fallback_edition(),
        # What THIS launcher makes of each probe label. `cp1252x` must map to None on
        # every surface — that entry is the policy pin: an unknown label is refused,
        # never quietly decoded as UTF-8 (which is what Node used to do, handing the
        # caller the wrong text with no error at all).
        "encodings": {
            label: _native.resolve_encoding_label(label) for label in _ENCODING_PROBES
        },
    }


def main(argv: list[str] | None = None) -> int:
    argv = list(sys.argv[1:] if argv is None else argv)

    if "--readme" in argv or "-h" in argv or "--help" in argv:
        return _print_readme()

    if argv[:1] == ["census"]:
        print(json.dumps(census(), indent=2))
        return 0

    p = _build_parser()
    argv = _with_default_subcommand(argv, p)

    try:
        args, extra = p.parse_known_args(argv)
    except SystemExit:
        return 5  # a clap-style "bad args" — argparse would exit 2 otherwise

    if extra:
        print(f"error: unexpected argument {extra[0]!r}", file=sys.stderr)
        return 5
    if getattr(args, "cmd", None) is None:
        print("error: a subcommand or input file is required", file=sys.stderr)
        return 5

    # `--dict` is now a real custom-dictionary overlay (#568): each verb threads it into
    # the native engine (validate/fix) or the library (certify), so there is no refusal
    # here any more. The dict's own errors (unreadable file, malformed dict,
    # `--dict-replace` + `--dict-version`) surface as exit 5 from the engine, in its words.
    if getattr(args, "json", False) and getattr(args, "ndjson", False):
        print("error: --json and --ndjson are mutually exclusive", file=sys.stderr)
        return 5

    if args.cmd == "rules":
        return _list_rules(args.json)
    if args.cmd == "read":
        return _run_read(args)
    if args.cmd == "pack":
        return _run_pack(args)
    if args.cmd == "unpack":
        return _run_unpack(args)
    if args.cmd == "lock":
        return _run_lock(args)
    if args.cmd == "unlock":
        return _run_unlock(args)
    if args.cmd == "excel":
        return _run_excel(args)
    if args.cmd == "diff":
        return _run_diff(args)
    if args.cmd == "merge":
        return _run_merge(args)
    if args.cmd == "fix":
        return _run_fix(args)
    if args.cmd == "certify":
        return _run_certify(args)
    return _run_validate(args)


if __name__ == "__main__":  # pragma: no cover - module entry point
    raise SystemExit(main())
